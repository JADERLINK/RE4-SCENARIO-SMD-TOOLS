using SimpleEndianBinaryIO;
using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace SHARED_SCENARIO_SMD.SCENARIO_REPACK
{
    public static class PutEmptyTpl
    {
        public static void PutTpl(Stream stream, long startOffset, out long endOffset, bool IsGcWii, bool IsPS4NS, Endianness endianness)
        {
            stream.Position = startOffset;
            if (IsGcWii)
            {
                stream.Write(TPL_GCWII, 0, TPL_GCWII.Length);
            }
            else if (IsPS4NS)
            {
                stream.Write(TPL_PS4NS, 0, TPL_PS4NS.Length);
            }
            else if (endianness == Endianness.BigEndian)
            {
                stream.Write(TPL_X360SP3, 0, TPL_X360SP3.Length);
            }
            else
            {
                stream.Write(TPL_UHD, 0, TPL_UHD.Length);
            }
            endOffset = stream.Position;
        }

        private static readonly byte[] TPL_GCWII = {
        0x00, 0x20, 0xAF, 0x30, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x00, 0x00, 0x00, 0x14,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0x40,
        0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
        };

        private static readonly byte[] TPL_X360SP3 = {
        0x78, 0x56, 0x34, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x00, 0x00, 0x00, 0x00
        };

        private static readonly byte[] TPL_UHD = {
        0x12, 0x34, 0x56, 0x78, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
        };

        private static readonly byte[] TPL_PS4NS = {
        0x78, 0x56, 0x34, 0x12, 0x00, 0x00, 0x00, 0x00, 0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
        };
     
    }
}
